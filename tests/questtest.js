const puppeteer = require('puppeteer-core');
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--allow-file-access-from-files'] });
  const page = await browser.newPage();
  const errs = [];
  page.on('pageerror', e => errs.push('PAGEERR ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await page.goto('file://' + require('path').resolve(__dirname, '../game/index.html'));
  await sleep(1000);
  const out = await page.evaluate(async () => {
    const log = [];
    window.__menu = [];
    window.__pick = 0;
    Dlg.say = (sp, text, opts) => Promise.resolve(opts && opts.choices ? window.__pick : 0);
    Menu.list = (o) => {
      const want = window.__menu.shift();
      if (want === undefined) return Promise.resolve(-1);
      const i = o.items.findIndex(it => it.label.includes(want));
      if (i < 0) { log.push('  !! menu item not found: ' + want + ' in [' + o.items.map(x => x.label).join(' | ') + ']'); return Promise.resolve(-1); }
      if (o.items[i].disabled) { log.push('  !! menu item disabled: ' + want + ' (' + (o.items[i].whyNot || '') + ')'); return Promise.resolve(-1); }
      return Promise.resolve(i);
    };
    window.wait = () => Promise.resolve();
    Game.fadeTo = () => Promise.resolve();
    Game.goto = (id) => { log.push('  -> goto ' + id); return Promise.resolve(); };
    const obj = (def, label) => def.objects.find(o => (typeof o.label === 'function' ? o.label() : o.label).includes(label));
    const act = async (def, label) => { const o = obj(def, label); if (!o) { log.push('  !! no object ' + label); return; } if (o.when && !o.when()) log.push('  !! object hidden: ' + label); await o.act(Game.scenes[def.id]); };
    const step = async (name, fn, menu) => { window.__menu = menu || []; await fn(); log.push(name.padEnd(28) + ' coins=' + S.coins + ' boat=' + S.boat + ' | ' + objectives()[0]); };
    S = newState();
    await step('read log', () => act(COTTAGE, 'logbook'));
    await step('take rod', () => act(COTTAGE, 'fishing rod'));
    await step('drawer', () => act(COTTAGE, 'drawer'));
    await step('rosa first', () => talkRosa(), ['Leave']);
    await step('greta first', () => talkGreta());
    S.inv.herring = 3; S.inv.mackerel = 1;
    await step('sell fish to tam', () => talkTam(), ['Sell all', 'Done']);
    await step('buy rowboat', () => talkBo(), ['Buy rowboat', 'Leave']);
    log.push('  route home->gull: ' + routeBlock('saltmere', 'gull') + ' / ->coconut: ' + routeBlock('saltmere', 'coconut'));
    await step('gull nest', () => act(GULL, 'nest'));
    await step('gull scratches', () => act(GULL, 'scratches'));
    S.coins += 40;
    await step('buy sail', () => talkBo(), ['Fit Pip', 'Leave']);
    log.push('  route home->coconut: ' + routeBlock('saltmere', 'coconut') + ' / ->lighthouse: ' + routeBlock('saltmere', 'lighthouse'));
    await step('mira first', () => talkMira());
    await step('oyster 1', () => act(PEARL, 'Open oysters'));
    PEARL.objects.filter(o => o.label === 'Open oysters').forEach(() => {});
    for (let i = 1; i < 3; i++) await PEARL.objects.filter(o => o.label === 'Open oysters')[i].act();
    log.push('  pearls: ' + Inv.count('pearl'));
    await step('shell', () => act(PEARL, 'shell'));
    await step('nell shell', () => talkNell());
    await step('nell shell 2', () => talkNell());
    await step('buy honey', () => talkRosa(), ['honey', 'Leave']);
    await step('trade sail', () => talkMira(), ['storm sail', 'Leave']);
    log.push('  route coconut->lighthouse: ' + routeBlock('coconut', 'lighthouse'));
    await step('bram first', () => talkBram());
    await step('ask bo teeth', () => talkBo(), ['Ask about the Teeth', 'Leave']);
    for (const o of COCONUT.objects.filter(o => o.label === 'Ironwood tree')) await o.act();
    log.push('  ironwood: ' + Inv.count('ironwood'));
    S.coins += 60;
    await step('reinforce hull', () => talkBo(), ['Reinforce hull', 'Leave']);
    await step('buy oil', () => talkHollis(), ['Lamp oil', 'Leave']);
    await step('mira wick', () => talkMira(), ['wick', 'Leave']);
    log.push('  route lighthouse->hollow (no lantern): ' + routeBlock('lighthouse', 'hollow'));
    await step('light lamp', () => act(LAMPROOM, 'lamp'));
    await step('bram lantern', () => talkBram());
    S.inv.bread = 5;
    log.push('  route lighthouse->hollow: ' + routeBlock('lighthouse', 'hollow') + ' hollowKnown=' + locKnown('hollow'));
    await step('bottle at lighthouse', () => act(LIGHTHOUSE, 'bottle'));
    await step('wreck', () => act(HOLLOW, 'wreck'));
    await step('find ansel', () => act(HOLLOW, 'fire'));
    log.push('  cove visible: ' + !!obj(HOLLOW, 'cove').when());
    log.push('  bottles: ' + JSON.stringify(S.bottles) + ' food=' + Inv.food());
    return log.join('\n');
  });
  console.log(out);
  console.log(errs.join('\n') || 'no errors');
  await browser.close();
})();
