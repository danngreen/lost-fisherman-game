const puppeteer = require('puppeteer-core');
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--allow-file-access-from-files'] });
  const page = await browser.newPage();
  const errs = [];
  page.on('pageerror', e => errs.push('PAGEERR ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await page.goto('file://' + require('path').resolve(__dirname, '../game/index.html'));
  await sleep(1000);
  const out = await page.evaluate(async () => {
    const log = [];
    window.__menu = []; window.__pick = 0;
    Dlg.say = (sp, text, opts) => Promise.resolve(opts && opts.choices ? window.__pick : 0);
    Menu.list = (o) => {
      const want = window.__menu.shift();
      if (want === undefined) return Promise.resolve(-1);
      const i = o.items.findIndex(it => (typeof it.label === 'function' ? it.label() : it.label).includes(want));
      if (i < 0) { log.push('  !! menu item not found: ' + want); return Promise.resolve(-1); }
      if (o.items[i].disabled) { log.push('  !! disabled: ' + want + ' (' + (o.items[i].whyNot || '') + ')'); return Promise.resolve(-1); }
      return Promise.resolve(i);
    };
    window.wait = () => Promise.resolve();
    Game.fadeTo = () => Promise.resolve();
    const gotos = [];
    Game.goto = (id, p) => { gotos.push(id); log.push('  -> goto ' + id); return Promise.resolve(); };
    const lbl = o => typeof o.label === 'function' ? o.label() : o.label;
    const act = async (def, label) => { const o = def.objects.find(o => lbl(o).includes(label)); if (!o) { log.push('  !! no object ' + label); return; } if (o.when && !o.when()) log.push('  !! hidden: ' + label); await o.act(Game.scenes[def.id]); };
    const step = async (name, fn, menu) => { window.__menu = menu || []; await fn(); log.push(name.padEnd(24) + ' $' + S.coins + ' | ' + objectives()[0]); };
    S = newState(2);
    log.push('start: boat=' + S.boat + ' food=' + Inv.food() + ' | ' + objectives()[0]);
    log.push('  known north? ' + locKnown('puffin') + '  route->lighthouse: ' + routeBlock('saltmere', 'lighthouse'));
    await step('find compass', () => c2FindCompass());
    await step('attic trunk', () => act(C2_COTTAGE, 'attic'));
    await step('ansel photo', () => c2Ansel());
    await step('bram chart', () => c2Bram());
    log.push('  route lighthouse->puffin: ' + routeBlock('lighthouse', 'puffin') + ' | ->floe: ' + routeBlock('puffin', 'floe'));
    S.inv.bread = 6;
    await step('meet ylva', () => c2Ylva());
    S.inv.herring = 3;
    await step('ylva herring', () => c2Ylva());
    await step('scrap before oskar', () => act(CANNERY, 'scrap'));
    await step('meet oskar', () => c2Oskar());
    await step('scrap heap', () => act(CANNERY, 'scrap'));
    S.coins += 30;
    await step('bo ice bow', () => c2Bo(), ['Forge', 'Leave']);
    log.push('  route cannery->floe: ' + routeBlock('cannery', 'floe'));
    window.__pick = 0;
    await step('seal pup', () => act(FLOE, 'seal'));
    await step('the wren', () => act(FLOE, 'frozen'));
    await step('buy grease', () => c2Hollis(), ['grease', 'Leave']);
    await step('oskar wren', () => c2Oskar());
    await step('ansel hartley', () => c2Ansel());
    const nsc = Game.scenes.narrows;
    const winch = c2Winch(nsc);
    await new Promise(r => setTimeout(r, 50));
    log.push('  crank active: ' + !!nsc.crank);
    nsc.crank.p = 2; NARROWS.update(nsc, 0.016);
    await winch;
    log.push('winch'.padEnd(24) + ' $' + S.coins + ' | ' + objectives()[0]);
    log.push('  grotto known: ' + locKnown('grotto') + ' departure: ' + JSON.stringify(chap().departure('narrows', 'grotto')));
    setFlag('grottoReached'); setFlag('calfLit');
    await step('tin box', () => act(GROTTO, 'tin box'));
    await step('nell feather', () => { S.inv.feather = 1; setFlag('nellAsk'); return c2Nell(); });
    log.push('  pages: ' + JSON.stringify(S.bottles) + ' items: ' + Object.keys(S.inv).join(','));
    await step('head home', () => c2HeadHome());
    await c2Ending();
    log.push('ending: ended=' + flag('ended') + ' scene=' + Game.sceneId + ' unlocked2=' + Save.isUnlocked(2));
    return log.join('\n');
  });
  console.log(out);
  console.log(errs.join('\n') || 'no errors');
  await browser.close();
})();
